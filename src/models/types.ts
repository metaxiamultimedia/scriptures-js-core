/**
 * Core type definitions for the scriptures library.
 */

/**
 * Morphological code describing grammatical features of a word.
 */
export interface Morphology {
  code: string;
  description?: string;
}

/**
 * An entry in a lexicon describing a lemma and its definition.
 */
export interface LexiconEntry {
  /** Source lexicon identifier (e.g., "stepbible-tbesh") */
  source?: string;
  /** Extended Strong's number (e.g., H0001a, G3056) */
  strongsExtended?: string;
  /** Disambiguated Strong's number */
  strongsDisambiguated?: string;
  /** Unified Strong's number */
  strongsUnified?: string;
  /** Lemma in original language (Hebrew/Greek Unicode) */
  lemma: string;
  /** Transliteration (romanized form) */
  transliteration?: string;
  /** Morphology code (e.g., "H:N-M" for Hebrew Noun-Masculine) */
  morphology?: string;
  /** Brief gloss (1-2 word meaning) */
  gloss?: string;
  /** Full definition */
  definition?: string;
}

/**
 * The kind of entity a proper noun refers to.
 * Mirrors STEPBible TIPNR categories.
 */
export type ProperNounType = 'person' | 'place' | 'place+person' | 'other';

/**
 * A single name form (spelling / language / variant) of a proper noun.
 * Derived from a TIPNR sub-record line (e.g. "– Named", "– Greek", "– Spelled").
 */
export interface ProperNounName {
  /** Significance / form type, e.g. "Named", "Greek", "Spelled", "Aramaic", "Total" */
  significance: string;
  /** Unique name key, e.g. "Abram|Abraham@Gen.11.26-1Pe" or "Aaron@Exo.4.14-Heb" */
  uniqueName: string;
  /** Disambiguated Strong's number for this form, e.g. "H0175" */
  strongsDisambiguated?: string;
  /** Extended Strong's number for this form, e.g. "H0175" */
  strongsExtended?: string;
  /** Original-language form (Hebrew/Greek Unicode), e.g. "אַהֲרֹן" */
  lemma?: string;
  /** Translated/English name as used in ESV (with KJV,NIV where they differ) */
  translation?: string;
  /** Scripture references for this name form, e.g. ["Exo.4.14", "Exo.4.27"] */
  refs: string[];
}

/**
 * A proper noun from scripture: an individual person, place, or thing,
 * unified across all of its name forms and tagged with a unified Strong's number.
 */
export interface ProperNoun {
  /** Source identifier (e.g., "stepbible-tipnr") */
  source?: string;
  /** Unified Strong's number — the unique id for this individual/place (e.g. "H0175") */
  id: string;
  /** Most common English name (e.g. "Aaron") */
  name: string;
  /** Full unique key with first-occurrence reference (e.g. "Aaron@Exo.4.14-Heb") */
  uniqueName: string;
  /** Kind of entity */
  type: ProperNounType;
  /** For persons: gender when known */
  gender?: 'male' | 'female';
  /** Short descriptive label from the record head line */
  description?: string;
  /** All name/spelling/language forms for this entity */
  names: ProperNounName[];
  /** All disambiguated Strong's numbers associated with this entity */
  strongs: string[];
  /** All scripture references where this entity occurs (aggregated, de-duplicated) */
  refs: string[];
  /**
   * Descriptions at increasing length. These were generated by an AI
   * (Claude 3 Opus, per STEPBible) and adapted by STEPBible — see the package README.
   */
  descriptions?: {
    briefest?: string;
    brief?: string;
    short?: string;
    article?: string;
  };
  /** Raw STEPBible summary field, retaining <strong=…>/<ref=…>/<br> markup */
  summary?: string;
  /** Genealogy (persons) — values are uniqueName keys of other proper nouns */
  parents?: string[];
  siblings?: string[];
  partners?: string[];
  offspring?: string[];
  /** Tribe / nation of the father (persons) */
  tribe?: string;
  /** Place name used by OpenBible.info (places) */
  openBibleName?: string;
  /** Founders / origin (places) — uniqueName keys */
  founders?: string[];
  /** People living there (places) — uniqueName keys */
  inhabitants?: string[];
  /** Google Maps URL for the geolocation (places) */
  googleMapUrl?: string;
  /** Palestine Open Maps URL (places) */
  palopenmapsUrl?: string;
  /** Geographical area / tribal territory (places) */
  geographicalArea?: string;
}

/**
 * Metadata for a proper-noun (names) source.
 */
export interface ProperNounMetadata {
  /** Source identifier (e.g., "stepbible-tipnr") */
  id: string;
  /** Display name */
  name: string;
  /** License information */
  license: string;
  /** Source attribution */
  source?: string;
  /** Source URLs */
  urls?: string[];
}

/**
 * Metadata for a lexicon source.
 */
export interface LexiconMetadata {
  /** Lexicon identifier (e.g., "stepbible-tbesh") */
  id: string;
  /** Display name */
  name: string;
  /** Language this lexicon covers */
  language: 'hebrew' | 'greek';
  /** License information */
  license: string;
  /** Source attribution */
  source?: string;
  /** Source URLs */
  urls?: string[];
}

/**
 * Stores mapping from English word to source language word/component.
 */
export interface Alignment {
  targetEdition: string;
  targetBook: string;
  targetChapter: number;
  targetVerse: number;
  targetPositions: number[];
  targetTexts: string[];
  targetPart?: string;
  targetPartText?: string;
  targetStrongs?: string[];
  confident: boolean;
  method: string;
  notes?: string;
}

/**
 * Gematria values for different calculation methods.
 */
export interface GematriaValues {
  standard: number;
  ordinal: number;
  reduced: number;
  [key: string]: number;
}

/**
 * Options for verse gematria calculation.
 */
export interface VerseGematriaOptions {
  /**
   * Which variant to use for Qere/Ketiv words.
   * - 'qere': use the traditional reading (default)
   * - 'ketiv': use the written consonantal text
   */
  variant?: 'qere' | 'ketiv';

  /**
   * Whether to include colophon words in the calculation.
   * Default: false
   */
  includeColophons?: boolean;
}

/**
 * Word metadata including colophon information.
 */
export interface WordMetadata {
  colophon?: boolean;
  colophonType?: string;
  [key: string]: unknown;
}

/**
 * A word token appearing in a Verse.
 */
export interface Word {
  position: number;
  text: string;
  lexiconEntry?: LexiconEntry;
  morphology?: Morphology;
  metadata?: WordMetadata;
  strongs?: string[];
  alignment?: Alignment;
  gematria?: GematriaValues;
  lemma?: string | string[];
  morph?: string;
  strong?: string;

  /**
   * True if this word is part of a colophon (subscription at end of epistles).
   * Colophon words are excluded from default gematria calculations.
   */
  isColophon?: boolean;

  /**
   * For Qere/Ketiv variants, indicates which reading this word represents.
   * - 'ketiv': the written consonantal text
   * - 'qere': the traditional vocalized reading
   * Mutually exclusive. Most words have no variant (undefined).
   */
  variant?: 'ketiv' | 'qere';
}

/**
 * Verse metadata including colophon information.
 */
export interface VerseMetadata {
  hasColophon?: boolean;
  colophonWordRange?: [number, number];
  colophonType?: string;
  [key: string]: unknown;
}

/**
 * Single verse of scripture identified by chapter and number.
 */
export interface Verse {
  id?: string;
  book?: string;
  chapter: number;
  number: number;
  text?: string;
  words: Word[];
  /** Gematria computed from words, excluding colophons and using Qere */
  gematria?: GematriaValues;
  /** Gematria computed from full verse text, including colophons */
  gematriaWithColophons?: GematriaValues;
  /**
   * Get gematria with custom options.
   * @param options - Options for variant selection and colophon inclusion
   * @returns GematriaValues proxy that computes on property access
   */
  getGematria?: (options: VerseGematriaOptions) => GematriaValues;
  metadata?: VerseMetadata;
}

/**
 * A chapter containing verses.
 */
export interface Chapter {
  chapter: number;
  verses: Verse[];
}

/**
 * A book of scripture.
 */
export interface Book {
  name: string;
  order: number;
  chapters: Map<number, Chapter>;
}

/**
 * A complete scripture text (e.g., KJV or Masoretic Text).
 */
export interface Scripture {
  name: string;
  language: string;
  abbreviation?: string;
  books: Book[];
}

/**
 * A collection of books forming a canon (e.g., Old Testament).
 */
export interface Canon {
  name: string;
  description?: string;
  books: Book[];
}

/**
 * Metadata for a scripture edition.
 */
export interface EditionMetadata {
  abbreviation: string;
  name: string;
  language: string;
  license: string;
  source?: string;
  urls?: string[];
  /** Year of publication or translation */
  year?: number;
  /** Edition name (e.g., "Oxford", "Cambridge") */
  edition?: string;
}

/**
 * A source citation for a cipher/gematria system.
 *
 * This is the shared, canonical citation shape used across every language's
 * cipher catalog (Hebrew, Greek, English, Latin) and consumed by `getAllCiphers()`.
 * It is a structural superset of the per-language citation shapes
 * (`hebrew/gematria/types.ts` `SourceCitation`, `gematria/greek.ts`
 * `GreekSourceCitation`), which own the data; their records are assignable to
 * this one without loss, including the original-language quote subfields.
 */
export interface SourceCitation {
  /** Source text name (e.g., "Jewish Encyclopedia (1903)") */
  text: string;
  /** Section reference (e.g., "E.3", "Bk II ch. XX") */
  section?: string;
  /** Page number */
  page?: number;
  /** URL to the source */
  url?: string;
  /** Exact quote from the source (English, or the original where no language-specific field applies) */
  quote?: string;
  /** Original-language quote, Hebrew */
  quoteHebrew?: string;
  /** Original-language quote, Greek */
  quoteGreek?: string;
  /** English translation of the original-language quote */
  translation?: string;
  /** Additional notes about derivation / caveats */
  note?: string;
}

/** The mechanical family a cipher belongs to. */
export type CipherKind = 'gematria' | 'isopsephy' | 'temurah';

/** The alphabet a cipher operates on. */
export type CipherLanguage = 'hebrew' | 'greek' | 'english' | 'latin';

/**
 * Detailed, JSON-serializable metadata for a single cipher/gematria system.
 *
 * This is the unified "detailed source information" record returned by
 * `getAllCiphers()` / `getCipher()`. It holds all three mechanical flavors:
 * a numeric letter→value table (`values`), a letter→letter substitution
 * (`mapping`, temurah), or a derived computation (`computed`, e.g. digital root).
 *
 * Entries carry NO function references so they can be handed to agents (via the
 * site's MCP layer) as plain data; compute functions live in their own modules,
 * linked by `id`/`aliases`.
 */
export interface CipherCatalogEntry {
  /** Canonical stable id, `${language}-${kebab-name}` (e.g. "hebrew-mispar-hechrachi"). */
  id: string;
  /** Alphabet the cipher operates on. */
  language: CipherLanguage;
  /** Mechanical family. */
  kind: CipherKind;
  /** Canonical display name. */
  name: string;
  /** Name in the system's own script (e.g. Hebrew "מספר הכרחי", Greek "ἰσοψηφία"). */
  nativeName?: string;
  /** English name (e.g. "Standard Value"). */
  englishName?: string;
  /** Other slugs/keys this system is known by (legacy Map slugs, site keys). */
  aliases?: string[];
  /** Human description of the system. */
  description: string;
  /** Structured provenance. Optional only while some systems' citations are still being backfilled. */
  source?: SourceCitation;
  /** Letter→number table (for table-based ciphers). */
  values?: Record<string, number>;
  /** Letter→letter substitution (for temurah ciphers). */
  mapping?: Record<string, string>;
  /** True when the value is derived by computation (e.g. digital root), not a static table. */
  computed?: boolean;
}

/**
 * Raw verse data as stored in JSON files.
 */
export interface VerseData {
  id?: string;
  text?: string;
  words?: Word[];
  gematria?: GematriaValues;
  metadata?: VerseMetadata;
}
